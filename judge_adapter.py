"""Judge adapter for the Genesis FinTech check definitions (published 20 Nov 2026).

Working directory: the repository root (``/app`` in the container). Import it as ``judge_adapter``.

    generate_episode(seed, config, output_dir) -> None     jury-side: writes one episode
    make_env()                                -> env       env.reset(seed, config) / env.step(action)
    score_episode(episode_dir, findings, inspection_steps) -> dict   jury-side closed evaluator call

* ``make_env()`` returns a thin client. The environment and its evaluator run in a separate
  process (``python -m auditenv.server``); the client object holds no truth, no provenance and
  no grader. The policy (run by the jury in its own restricted process) only ever receives the
  observations that ``step`` returns.
* ``reset(seed, config)``: ``config={"mode": "closed", "episode_dir": DIR, "team_config": {...}}``
  loads exactly that episode (no generation, no id changes); a repeated reset restarts it.
  ``mode="train"`` is the open training mode. Without ``episode_dir`` the team generator is used
  with ``seed`` and ``team_config`` (our generator config, see README "Генератор").
* Actions: ``{"name": "<list_records|get_record|get_document|calculator|submit>", "args": {...}}``.
* Observations: first ``{"task", "manifest", "policy", "remaining_steps": 100}``, then
  ``{"result": value_or_null, "error": null_or_{code, message}, "remaining_steps": int}``.
  list_records -> ``{"records": [...], "next_cursor": str|null}``; get_record / get_document -> the
  record / document object; calculator -> decimal string; submit -> ``{"accepted": true}`` or a
  structure error ``{"code": "invalid_submission", ...}`` (never correctness).
* Closed mode: reward is 0.0 at every step including the terminal one, info is ``{}``; the grade is
  appended to the evaluator log (``AUDITENV_EVALUATOR_LOG`` or ``<tmp>/auditenv-evaluator.jsonl``)
  and is available to the jury via ``env.last_evaluation()``.
* Episode layout written by ``generate_episode``: ``public/`` (manifest.json, ledger.csv,
  invoices.jsonl, payments.jsonl, fx.csv, policy.json) and ``private/`` (truth.json,
  provenance.json). ``reset``/``score_episode`` also accept all eight files flat in one directory.
* The secret salt for closed seeds is read from ``AUDITENV_SECRET`` (jury-side only).
"""
from __future__ import annotations

import copy
import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

ROOT = Path(__file__).resolve().parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

ACTION_NAMES = ("list_records", "get_record", "get_document", "calculator", "submit")
TABLES = ("ledger", "invoices", "payments", "fx")
METRIC_KEYS = ("tp", "fp", "fn", "precision", "recall", "f1")


def evaluator_log_path() -> str:
    return os.environ.get("AUDITENV_EVALUATOR_LOG") or str(Path(tempfile.gettempdir()) / "auditenv-evaluator.jsonl")


def _append_log(record: Dict[str, Any]) -> None:
    path = evaluator_log_path()
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, sort_keys=True, ensure_ascii=False) + "\n")


def _team_config(config: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    config = dict(config or {})
    if "team_config" in config:
        return copy.deepcopy(config["team_config"] or {})
    for k in ("mode", "episode_dir"):
        config.pop(k, None)
    return config


# ------------------------------------------------------------------ generate
def generate_episode(seed: int, config: dict, output_dir: str) -> None:
    """Write one episode (public/ + private/) generated by the team generator into ``output_dir``."""
    from auditenv.generator import generate_episode as _generate
    ep = _generate(int(seed), _team_config(config), secret=os.environ.get("AUDITENV_SECRET", ""))
    ep.write(output_dir)


# ---------------------------------------------------------------------- env
class JudgeEnv:
    """Client of the out-of-process environment, speaking the judge envelope."""

    def __init__(self, time_limit_s: float = 60.0) -> None:
        from auditenv.remote import RemoteAuditEnv
        self._log = evaluator_log_path()
        Path(self._log).parent.mkdir(parents=True, exist_ok=True)
        self._remote = RemoteAuditEnv(self._log, mode="eval", secret=os.environ.get("AUDITENV_SECRET", ""),
                                      time_limit_s=time_limit_s)
        self._closed = True

    # -- reset
    def reset(self, seed: Optional[int] = None, config: Optional[Dict[str, Any]] = None,
              options: Optional[Dict[str, Any]] = None) -> Tuple[Dict[str, Any], Dict[str, Any]]:
        config = dict(config or (options or {}).get("config") or {})
        mode = config.get("mode", "closed")
        if mode not in ("closed", "train"):
            raise ValueError("config.mode must be 'closed' or 'train'")
        self._closed = mode == "closed"
        if config.get("episode_dir"):
            team = {"episode_dir": str(config["episode_dir"])}
        else:
            team = _team_config(config)
        obs, info = self._remote.reset(seed=seed, config=team, mode="eval" if self._closed else "train")
        first = {"task": obs["task"], "manifest": obs["manifest"], "policy": obs["policy"],
                 "remaining_steps": obs["steps_remaining"]}
        return first, {"env_version": info.get("env_version"), "schema_version": info.get("schema_version"),
                       "mode": mode}

    # -- step
    def step(self, action: Any) -> Tuple[Dict[str, Any], float, bool, bool, Dict[str, Any]]:
        inner = self._translate_action(action)
        obs, reward, terminated, truncated, info = self._remote.step(inner)
        out = self._translate_observation(obs)
        if self._closed:
            reward, info = 0.0, {}
        return out, float(reward), bool(terminated), bool(truncated), info

    @staticmethod
    def _translate_action(action: Any) -> Any:
        if isinstance(action, (str, bytes)):
            try:
                action = json.loads(action)
            except (ValueError, TypeError, RecursionError):
                return "<not json>"  # the environment answers with a bounded invalid_action error
        if not isinstance(action, dict) or "name" not in action or set(action) - {"name", "args"}:
            return {"action": None}  # bounded invalid_action error, step consumed
        out = {"action": action["name"]}
        if "args" in action:
            out["args"] = action["args"]
        return out

    @staticmethod
    def _translate_observation(obs: Dict[str, Any]) -> Dict[str, Any]:
        remaining = obs.get("steps_remaining", 0)
        kind = obs.get("kind")
        result: Any = None
        error: Any = None
        if kind == "result":
            res, act = obs["result"], obs.get("action")
            if act == "list_records":
                result = {"records": res["records"], "next_cursor": res["next_cursor"]}
            elif act == "get_record":
                result = res["record"]
            elif act == "get_document":
                result = res["document"]
            elif act == "calculator":
                result = res["result"]
            else:  # pragma: no cover
                result = res
        elif kind == "error":
            error = {"code": obs["error"]["code"], "message": obs["error"]["message"]}
        elif kind == "submitted":
            r = obs.get("result") or {}
            if r.get("status") == "invalid_submission":
                error = {"code": "invalid_submission",
                         "message": ("findings do not follow findings.schema.json: " + r.get("error", ""))[:300]}
            else:
                result = {"accepted": True}
        elif kind == "truncated":
            error = {"code": obs.get("reason", "time_limit"),
                     "message": "The 60 s episode time limit was reached; the final answer is empty."}
        if obs.get("episode_end") and error is None and kind != "error":
            pass  # step limit: the 100th action's own result is returned, truncated=True
        return {"result": result, "error": error, "remaining_steps": remaining}

    # -- jury-side helpers (never handed to a policy)
    def last_evaluation(self) -> Optional[Dict[str, Any]]:
        """Last grade written by the evaluator process (closed and train runs)."""
        try:
            lines = Path(self._log).read_text(encoding="utf-8").splitlines()
        except OSError:
            return None
        return json.loads(lines[-1]) if lines else None

    def close(self) -> None:
        self._remote.close()

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()

    def __del__(self):  # pragma: no cover - best effort
        try:
            self.close()
        except Exception:
            pass


def make_env() -> JudgeEnv:
    return JudgeEnv()


# -------------------------------------------------------------------- score
def score_episode(episode_dir: str, findings: dict, inspection_steps: int) -> dict:
    """Closed evaluator call: grade ``findings`` against the episode's truth.

    Valid submission -> {"tp", "fp", "fn", "precision", "recall", "f1", "return"}; invalid structure ->
    {"return": -1, other keys null}; the full grade (with the error) goes to the evaluator log."""
    from auditenv.episode import Episode
    from auditenv.grader import Grader
    ep = Episode.load(episode_dir)
    try:
        payload = json.loads(json.dumps(findings, ensure_ascii=False))
    except (ValueError, TypeError, RecursionError):
        payload = None
    grade = Grader(ep.public(), ep.truth).grade(payload, int(inspection_steps), status="submitted")
    grade.update({"source": "score_episode", "episode_dir": str(episode_dir)})
    _append_log(grade)
    if grade["status"] == "invalid_submission":
        return {**{k: None for k in METRIC_KEYS}, "return": -1.0}
    return {**{k: grade[k] for k in METRIC_KEYS}, "return": grade["reward"]}


def oracle_findings(episode_dir: str) -> dict:
    """Jury-side convenience: the correct findings.json of an episode, built from its truth."""
    from auditenv.episode import Episode
    from auditenv.policies.oracle import oracle_findings as _oracle
    ep = Episode.load(episode_dir)
    return {"episode_id": ep.episode_id, "findings": _oracle(ep.truth)}


__all__ = ["generate_episode", "make_env", "score_episode", "oracle_findings", "JudgeEnv", "ACTION_NAMES", "TABLES"]
